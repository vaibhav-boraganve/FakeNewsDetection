EFFNET_PATH = settings.WEIGHTS_DIR / "image_efficientnet_b0.pt"
XCEPTION_PATH = settings.WEIGHTS_DIR / "xception_faces.pt"

AI_GENERATOR_MARKERS = (
    "stable diffusion", "midjourney", "dall-e", "dall·e", "firefly", "comfyui", "automatic1111",
    "novelai", "invokeai", "imagen", "generated by ai", "ai generated", "made with ai", "c2pa",
    "trainedalgorithmicmedia", "sdxl", "flux",
)
AI_CHUNK_KEYS = {"parameters", "prompt", "workflow", "negative_prompt", "sd-metadata", "dream"}
RESAMPLING_THRESHOLD = 12.0  # natural photos score ~6-9, interpolated images 25+
EDITOR_MARKERS = ("photoshop", "gimp", "lightroom", "snapseed", "canva", "picsart", "facetune", "pixlr", "affinity")


class ForensicAnalyzer:
    name = "Forensic analysis (ELA + noise + FFT + metadata)"

    @staticmethod
    def _block_stats(img: np.ndarray, block: int = 32) -> np.ndarray:
        h, w = img.shape[:2]
        hb, wb = h // block, w // block
        if hb < 2 or wb < 2:
            return np.array([float(img.mean())])
        cropped = img[: hb * block, : wb * block]
        return cropped.reshape(hb, block, wb, block).mean(axis=(1, 3)).ravel()

    @staticmethod
    def _outlier_z(values: np.ndarray, texture: np.ndarray) -> tuple[float, float]:
        """Regress a per-block statistic on block texture (log space) and return the robust
        z-score of the most anomalous blocks: natural images keep a consistent
        texture->statistic relationship, pasted regions break it."""
        v, t = np.log(values + 0.2), np.log(texture + 0.2)
        if v.size < 8:
            return 0.0, 0.0
        A = np.vstack([t, np.ones_like(t)]).T
        coef, *_ = np.linalg.lstsq(A, v, rcond=None)
        r = v - A @ coef
        mad = float(np.median(np.abs(r - np.median(r)))) * 1.4826 + 1e-3
        z = np.abs(r - np.median(r)) / mad
        return float(np.percentile(z, 99)), float((z > 3.5).mean())

    def _texture_blocks(self, gray: np.ndarray, sigma: float) -> np.ndarray:
        return self._block_stats(np.abs(cv2.Laplacian(cv2.GaussianBlur(gray, (0, 0), sigma), cv2.CV_32F)))

    def error_level(self, img: np.ndarray, gray: np.ndarray) -> dict:
        """Error Level Analysis: recompress as JPEG and look for regions whose error level
        does not match their texture (splicing / local editing cue)."""
        ok, buf = cv2.imencode(".jpg", img, [cv2.IMWRITE_JPEG_QUALITY, 90])
        ela = cv2.absdiff(img, cv2.imdecode(buf, cv2.IMREAD_COLOR)).astype(np.float32).mean(axis=2)
        z99, frac = self._outlier_z(self._block_stats(ela), self._texture_blocks(gray, 1.0))
        return {"ela_mean": round(float(ela.mean()), 4), "ela_inconsistency": round(z99, 4), "ela_outlier_fraction": round(frac, 4)}

    def noise_residual(self, img: np.ndarray, gray: np.ndarray) -> dict:
        """Median-filter noise residual vs. texture: inconsistent sensor noise hints at compositing."""
        residual = np.abs(gray - cv2.medianBlur(gray.astype(np.uint8), 3).astype(np.float32))
        z99, _ = self._outlier_z(self._block_stats(residual), self._texture_blocks(gray, 2.0))
        return {"noise_level": round(float(residual.mean()), 4), "noise_spread": round(z99, 4)}

    @staticmethod
    def resampling_score(gray: np.ndarray, exclude_jpeg_grid: bool) -> float:
        """Resampling / upsampling detector: interpolation makes the magnitude of the second
        derivative periodic, which appears as a sharp peak in its spectrum (Popescu & Farid).
        Generative models and resized/pasted content commonly leave this trace."""
        h, w = gray.shape
        n = min(512, h, w)
        n -= n % 16
        y0, x0 = (h - n) // 2, (w - n) // 2
        c = gray[y0 : y0 + n, x0 : x0 + n]
        best = 0.0
        for axis in (0, 1):
            prof = np.abs(np.diff(c, 2, axis=axis)).mean(axis=1 - axis)
            prof = prof - prof.mean()
            P = np.abs(np.fft.rfft(prof * np.hanning(len(prof))))
            f = np.arange(len(P))
            valid = f > len(P) * 0.1
            if exclude_jpeg_grid:
                grid = len(prof) / 8 * np.arange(1, 5)
                valid &= np.min(np.abs(f[:, None] - grid[None, :]), axis=1) > 1.5
            if valid.sum() < 4:
                continue
            best = max(best, float(P[valid].max() / (np.median(P[valid]) + 1e-6)))
        return best

    def spectrum(self, img: np.ndarray, is_jpeg: bool = True) -> dict:
        """Resampling periodicity + radial high-frequency energy (over-smoothed images have
        an abnormally weak high-frequency tail)."""
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
        peak = self.resampling_score(gray, exclude_jpeg_grid=is_jpeg)
        g = cv2.resize(gray, (256, 256), interpolation=cv2.INTER_AREA)
        g -= g.mean()
        mag = np.log1p(np.abs(np.fft.fftshift(np.fft.fft2(g * np.outer(np.hanning(256), np.hanning(256))))))
        y, x = np.indices(mag.shape)
        r = np.hypot(y - 128, x - 128).astype(int)
        radial = (np.bincount(r.ravel(), mag.ravel()) / np.maximum(np.bincount(r.ravel()), 1))[:128]
        hf_ratio = float(radial[64:].mean() / (radial[4:32].mean() + 1e-6))
        return {"hf_energy_ratio": round(hf_ratio, 4), "spectral_peak_score": round(peak, 4)}

    @staticmethod
    def metadata(data: bytes) -> dict:
        meta = read_metadata(data)
        blob = " ".join(
            [*(str(v) for v in meta["exif"].values()), *meta["text_chunks"].keys(), *(str(v) for v in meta["text_chunks"].values())]
        ).lower()
        ai_hit = any(m in blob for m in AI_GENERATOR_MARKERS) or bool(
            AI_CHUNK_KEYS & {k.lower() for k in meta["text_chunks"]}
        )
        editor_hit = any(m in blob for m in EDITOR_MARKERS)
        has_camera = bool(meta["exif"].get("Make") or meta["exif"].get("Model"))
        return {
            "format": meta["format"],
            "camera": " ".join(filter(None, [meta["exif"].get("Make"), meta["exif"].get("Model")])) or None,
            "software": meta["exif"].get("Software"),
            "ai_generator_signature": ai_hit,
            "editing_software_signature": editor_hit,
            "has_camera_exif": has_camera,
        }

    def face_consistency(self, img: np.ndarray, faces: list) -> dict | None:
        """Compare sharpness / noise inside the main face against its surroundings (blending cue)."""
        if not faces:
            return None
        x, y, w, h = faces[0]
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        face = gray[y : y + h, x : x + w]
        ctx = crop_face(gray[..., None], faces[0], margin=0.6)[..., 0]
        sharp = lambda a: float(cv2.Laplacian(a, cv2.CV_32F).var()) + 1e-3  # noqa: E731
        ratio = sharp(face) / sharp(ctx)
        return {"face_context_sharpness_ratio": round(ratio, 4)}

    def analyze(self, img: np.ndarray, data: bytes, faces: list) -> tuple[float, dict, list[str]]:
        meta = self.metadata(data)
        is_jpeg = (meta["format"] or "").upper() in {"JPEG", "MPO"}
        gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY).astype(np.float32)
        ela = self.error_level(img, gray)
        noise = self.noise_residual(img, gray)
        spec = self.spectrum(img, is_jpeg)
        face = self.face_consistency(img, faces)

        ela_n = clamp((ela["ela_inconsistency"] - 3.0) / 1.5) * (1.0 if is_jpeg else 0.6)
        noise_n = clamp((noise["noise_spread"] - 7.0) / 4.0)
        peak_n = clamp((spec["spectral_peak_score"] - RESAMPLING_THRESHOLD) / 15.0)
        smooth_n = clamp((0.55 - spec["hf_energy_ratio"]) / 0.2)
        face_n = 0.0
        if face:
            ratio = face["face_context_sharpness_ratio"]
            face_n = clamp((abs(np.log(ratio)) - 0.9) / 1.2)

        z = -1.1 + 2.0 * ela_n + 0.8 * noise_n + 2.4 * peak_n + 0.8 * smooth_n + 1.0 * face_n
        z += 4.0 if meta["ai_generator_signature"] else 0.0
        z += 0.8 if meta["editing_software_signature"] else 0.0
        z -= 0.8 if meta["has_camera_exif"] and not meta["editing_software_signature"] else 0.0
        prob = clamp(sigmoid(z), 0.03, 0.97)

        signals = []
        if meta["ai_generator_signature"]:
            signals.append("Metadata contains an AI image-generator signature")
        if meta["editing_software_signature"]:
            signals.append(f"Edited with image software ({meta['software'] or 'detected in metadata'})")
        if meta["has_camera_exif"]:
            signals.append(f"Camera EXIF present ({meta['camera']})")
        else:
            signals.append("No camera EXIF metadata")
        if ela_n > 0.4:
            signals.append("Uneven JPEG error levels across regions (possible splicing)")
        if noise_n > 0.4:
            signals.append("Inconsistent sensor-noise pattern across regions")
        if peak_n > 0.3:
            signals.append("Periodic resampling pattern (upscaled, generated or resized/pasted content)")
        if smooth_n > 0.5:
            signals.append("Unnaturally smooth high-frequency spectrum")
        if face_n > 0.4:
            signals.append("Face sharpness inconsistent with surroundings (blending artifact)")

        details = {**ela, **noise, **spec, "metadata": meta}
        if face:
            details.update(face)
        return prob, details, signals


class _TorchClassifier:
    def __init__(self, name: str, path, builder, size: int, mean=None, std=None):
        self.name, self.path, self.builder, self.size = name, path, builder, size
        self.mean, self.std = mean, std
        self.model = None
        self.status = "no-weights"
        self._lock = threading.Lock()

    def load(self) -> None:
        torch = get_torch()
        if torch is None:
            self.status = "unavailable"
            return
        if not self.path.exists():
            self.status = "no-weights"
            return
        try:
            from models.architectures import load_state_dict_flex

            model = self.builder()
            load_state_dict_flex(model, self.path)
            self.model = model.eval().to(get_device())
            self.status = "ready"
        except Exception as exc:
            self.status = "failed"
            log.warning("Could not load %s: %s", self.path.name, exc)

    @property
    def ready(self) -> bool:
        return self.model is not None

    def predict_batch(self, crops: list[np.ndarray]) -> float:
        torch = get_torch()
        kwargs = {"mean": self.mean, "std": self.std} if self.mean is not None else {}
        x = np.stack([resize_and_normalize(c, self.size, **kwargs) for c in crops])
        with self._lock, torch.inference_mode():
            probs = torch.softmax(self.model(torch.from_numpy(x).to(get_device())), dim=-1)[:, 1]
        return float(probs.mean().item())


def _build_effnet():
    from models.architectures import build_efficientnet_b0

    return build_efficientnet_b0()


def _build_xception():
    from models.architectures import build_xception

    return build_xception()


class ImageDetector:
    modality = "image"

    def __init__(self) -> None:
        self.forensics = ForensicAnalyzer()
        self.effnet = _TorchClassifier("EfficientNet-B0 CNN", EFFNET_PATH, _build_effnet, 224)
        self.xception = _TorchClassifier(
            "XceptionNet (faces)", XCEPTION_PATH, _build_xception, 299, XCEPTION_MEAN, XCEPTION_STD
        )

    def load(self) -> None:
        self.effnet.load()
        self.xception.load()

    def status(self) -> dict:
        return {"forensics": "ready", "efficientnet": self.effnet.status, "xception": self.xception.status}

    def predict_array(self, img: np.ndarray, data: bytes | None = None) -> DetectorOutput:
        if data is None:
            ok, buf = cv2.imencode(".png", img)
            data = buf.tobytes()
        faces = detect_faces(img)
        f_prob, f_details, signals = self.forensics.analyze(img, data, faces)

        used = [self.forensics.name]
        component = {self.forensics.name: round(f_prob * 100, 2)}
        scores = {"forensic": (f_prob, 1.0)}

        if self.effnet.ready:
            p = self.effnet.predict_batch([img])
            scores["effnet"] = (p, 2.0)
            component[self.effnet.name] = round(p * 100, 2)
            used.insert(0, self.effnet.name)
        if self.xception.ready and faces:
            p = self.xception.predict_batch([crop_face(img, b) for b in faces[:4]])
            scores["xception"] = (p, 2.0)
            component[self.xception.name] = round(p * 100, 2)
            used.insert(0, self.xception.name)

        mode = "deep-learning ensemble" if len(scores) > 1 else "forensic heuristics (no trained CNN weights found)"
        h, w = img.shape[:2]
        return DetectorOutput(
            prob_fake=weighted_ensemble(scores),
            models_used=used,
            details={
                "mode": mode,
                "component_fake_probabilities": component,
                "signals": signals,
                "faces_detected": len(faces),
                "resolution": f"{w}x{h}",
                "forensics": f_details,
            },
        )

    def predict(self, data: bytes) -> DetectorOutput:
        return self.predict_array(decode_image(data), data)

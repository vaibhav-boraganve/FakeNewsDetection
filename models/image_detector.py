"""Image forensics detector.

Ensemble of
  * EfficientNet-B0 binary classifier (whole image, synthetic / spliced visuals),
  * XceptionNet on detected face crops (facial manipulation artifacts),
  * classical forensic analysis that always runs: Error Level Analysis, noise-residual
    consistency, frequency-spectrum (GAN/diffusion upsampling) artifacts, metadata.

The CNNs are used when trained weights exist in models/weights/
(image_efficientnet_b0.pt, xception_faces.pt - see training/train_image.py). Without
them the detector falls back to the forensic analysis so it is runnable out of the box.
"""
